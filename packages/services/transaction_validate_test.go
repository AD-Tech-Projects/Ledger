func TestValidateCreateTransactionInputAcceptsWalletRules(t *testing.T) {
	tests := []struct {
		name            string
		transactionType domain.TransactionType
		withSource      bool
		withDestination bool
	}{
		{"deposit into destination", domain.TRANSACTION_DEPOSIT, false, true},
		{"withdrawal from source", domain.TRANSACTION_WITHDRAWAL, true, false},
		{"transfer between wallets", domain.TRANSACTION_TRANSFER, true, true},
		{"yield into destination", domain.TRANSACTION_YIELD, false, true},
		{"yield generated by source", domain.TRANSACTION_YIELD, true, true},
		{"sale without buyer", domain.TRANSACTION_SALE, false, true},
		{"sale with buyer", domain.TRANSACTION_SALE, true, true},
		{"fee without revenue wallet", domain.TRANSACTION_FEE, true, false},
		{"fee with revenue wallet", domain.TRANSACTION_FEE, true, true},
		{"purchase without seller", domain.TRANSACTION_PURCHASE, true, false},
		{"purchase with seller", domain.TRANSACTION_PURCHASE, true, true},
		{"reserve", domain.TRANSACTION_RESERVE, true, false},
		{"release", domain.TRANSACTION_RELEASE, true, false},
		{"hold", domain.TRANSACTION_HOLD, true, false},
		{"unhold", domain.TRANSACTION_UNHOLD, true, false},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			input := testInput(test.transactionType, 50, test.withSource, test.withDestination)
			if err := validateCreateTransactionInput(&input); err != nil {
				t.Fatal(err)
			}
		})
	}
}

func TestValidateCreateTransactionInputRejectsInvalidInput(t *testing.T) {
	originID := testOriginID
	invalidID := "not-a-uuid"
	sameID := testSourceWalletID

	tests := []struct {
		name  string
		input CreateTransactionInput
	}{
		{"unsupported type", testInput("UNKNOWN", 50, true, true)},
		{"zero amount", testInput(domain.TRANSACTION_TRANSFER, 0, true, true)},
		{"negative amount", testInput(domain.TRANSACTION_TRANSFER, -50, true, true)},
		{"deposit with source wallet", testInput(domain.TRANSACTION_DEPOSIT, 50, true, true)},
		{"deposit without destination wallet", testInput(domain.TRANSACTION_DEPOSIT, 50, false, false)},
		{"withdrawal with destination wallet", testInput(domain.TRANSACTION_WITHDRAWAL, 50, true, true)},
		{"withdrawal without source wallet", testInput(domain.TRANSACTION_WITHDRAWAL, 50, false, false)},
		{"transfer without destination wallet", testInput(domain.TRANSACTION_TRANSFER, 50, true, false)},
		{"yield without destination wallet", testInput(domain.TRANSACTION_YIELD, 50, true, false)},
		{"fee without source wallet", testInput(domain.TRANSACTION_FEE, 50, false, true)},
		{"reserve with destination wallet", testInput(domain.TRANSACTION_RESERVE, 50, true, true)},
		{"same source and destination wallet", CreateTransactionInput{Type: domain.TRANSACTION_TRANSFER, Amount: 50, SourceWalletID: &sameID, DestinationWalletID: &sameID}},
		{"invalid wallet id", CreateTransactionInput{Type: domain.TRANSACTION_DEPOSIT, Amount: 50, DestinationWalletID: &invalidID}},
		{"reversal origin on a non-reversal", CreateTransactionInput{Type: domain.TRANSACTION_TRANSFER, Amount: 50, SourceWalletID: &sameID, ReversalOriginID: &originID}},
		{"reversal without origin", CreateTransactionInput{Type: domain.TRANSACTION_REVERSAL}},
		{"reversal with invalid origin id", CreateTransactionInput{Type: domain.TRANSACTION_REVERSAL, ReversalOriginID: &invalidID}},
		{"reversal with wallets", CreateTransactionInput{Type: domain.TRANSACTION_REVERSAL, ReversalOriginID: &originID, SourceWalletID: &sameID}},
		{"reversal with negative amount", CreateTransactionInput{Type: domain.TRANSACTION_REVERSAL, Amount: -1, ReversalOriginID: &originID}},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			input := test.input
			if err := validateCreateTransactionInput(&input); !errors.Is(err, ErrInvalidTransaction) {
				t.Fatalf("expected invalid transaction error, got %v", err)
			}
		})
	}
}

func TestValidateCreateTransactionInputNormalizesOptionalFields(t *testing.T) {
	empty, blank, originID := "", "  ", testOriginID
	input := CreateTransactionInput{
		Type:                domain.TRANSACTION_REVERSAL,
		ReversalOriginID:    &originID,
		SourceWalletID:      &empty,
		DestinationWalletID: &blank,
		ReferenceID:         &blank,
		Description:         "  reversal  ",
	}

	if err := validateCreateTransactionInput(&input); err != nil {
		t.Fatal(err)
	}
	if input.SourceWalletID != nil || input.DestinationWalletID != nil || input.ReferenceID != nil {
		t.Fatalf("expected empty optional fields to be normalized to nil, got %+v", input)
	}
	if input.Description != "reversal" {
		t.Fatalf("expected trimmed description, got %q", input.Description)
	}
}

// NOTE - invalid transactions are rejected before any balance is changed.
func TestValidateTransactionRejectsInvalidTransactions(t *testing.T) {
	inactive := func(w *domain.Wallet) { w.Status = domain.WALLET_INACTIVE }
	otherAsset := func(w *domain.Wallet) { w.AssetID = "other-asset" }

	tests := []struct {
		name            string
		transactionType domain.TransactionType
		amount          int64
		withSource      bool
		withDestination bool
		sameWallet      bool
		changeSource    func(*domain.Wallet)
		changeDest      func(*domain.Wallet)
	}{
		{"deposit without destination wallet", domain.TRANSACTION_DEPOSIT, 50, false, false, false, nil, nil},
		{"deposit with source wallet", domain.TRANSACTION_DEPOSIT, 50, true, true, false, nil, nil},
		{"withdrawal without source wallet", domain.TRANSACTION_WITHDRAWAL, 50, false, false, false, nil, nil},
		{"zero amount", domain.TRANSACTION_TRANSFER, 0, true, true, false, nil, nil},
		{"negative amount", domain.TRANSACTION_TRANSFER, -50, true, true, false, nil, nil},
		{"same source and destination wallet", domain.TRANSACTION_TRANSFER, 50, true, true, true, nil, nil},
		{"wallets with different assets", domain.TRANSACTION_FEE, 50, true, true, false, nil, otherAsset},
		{"inactive source wallet", domain.TRANSACTION_TRANSFER, 50, true, true, false, inactive, nil},
		{"inactive destination wallet", domain.TRANSACTION_YIELD, 50, true, true, false, nil, inactive},
		{"unsupported transaction type", domain.TransactionType("UNKNOWN"), 50, true, true, false, nil, nil},
		{"reversal without origin", domain.TRANSACTION_REVERSAL, 50, true, true, false, nil, nil},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			source := newTestWallet("source", domain.WALLET_CHECKING, &balances{free: 100})
			destination := newTestWallet("destination", domain.WALLET_INVESTMENT, &balances{free: 100})
			if test.changeSource != nil {
				test.changeSource(source)
			}
			if test.changeDest != nil {
				test.changeDest(destination)
			}

			var sourceWallet, destinationWallet *domain.Wallet
			if test.withSource {
				sourceWallet = source
			}
			if test.withDestination {
				destinationWallet = destination
			}
			if test.sameWallet {
				destinationWallet = sourceWallet
			}

			err := validateTransaction(testTransaction(test.transactionType, test.amount, sourceWallet, destinationWallet))
			var validationErr *transactionValidationError
			if !errors.As(err, &validationErr) || !errors.Is(err, ErrInvalidTransaction) {
				t.Fatalf("expected transaction validation error, got %v", err)
			}

			assertBalances(t, "source", source, &balances{free: 100})
			assertBalances(t, "destination", destination, &balances{free: 100})
		})
	}
}

func TestValidateTransactionRejectsNilTransaction(t *testing.T) {
	if err := validateTransaction(nil); !errors.Is(err, ErrInvalidTransaction) {
		t.Fatalf("expected invalid transaction error, got %v", err)
	}
}

func TestValidateReversalRejectsInvalidOrigins(t *testing.T) {
	tests := []struct {
		name   string
		change func(origin *domain.Transaction, reversal *domain.Transaction)
	}{
		{"origin not completed", func(origin, _ *domain.Transaction) { origin.Status = domain.TRANSACTION_FAILED }},
		{"origin is a reversal", func(origin, _ *domain.Transaction) { origin.Type = domain.TRANSACTION_REVERSAL }},
		{"partial amount", func(_, reversal *domain.Transaction) { reversal.Amount = 10 }},
		{"wallets do not match the origin", func(_, reversal *domain.Transaction) {
			reversal.SourceWallet, reversal.DestinationWallet = reversal.DestinationWallet, reversal.SourceWallet
		}},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			source := newTestWallet("source", domain.WALLET_CHECKING, &balances{free: 100})
			destination := newTestWallet("destination", domain.WALLET_CHECKING, &balances{free: 100})
			origin := testTransaction(domain.TRANSACTION_TRANSFER, 50, source, destination)
			origin.Status = domain.TRANSACTION_COMPLETED
			reversal := testReversal(origin, source, destination)

			test.change(origin, reversal)

			if err := validateTransaction(reversal); !errors.Is(err, ErrInvalidTransaction) {
				t.Fatalf("expected invalid transaction error, got %v", err)
			}
		})
	}
}

func testInput(transactionType domain.TransactionType, amount int64, withSource bool, withDestination bool) CreateTransactionInput {
	input := CreateTransactionInput{Type: transactionType, Amount: amount}
	if withSource {
		sourceID := testSourceWalletID
		input.SourceWalletID = &sourceID
	}
	if withDestination {
		destinationID := testDestinationWalletID
		input.DestinationWalletID = &destinationID
	}
	return input
}
