type balances struct {
	free     int64
	reserved int64
	hold     int64
}

func TestApplyTransactionCases(t *testing.T) {
	tests := []struct {
		name            string
		transactionType domain.TransactionType
		source          *balances
		destination     *balances
		wantSource      *balances
		wantDestination *balances
	}{
		{"deposit into a single wallet", domain.TRANSACTION_DEPOSIT, nil, &balances{}, nil, &balances{free: 50}},
		{"withdrawal from a single wallet", domain.TRANSACTION_WITHDRAWAL, &balances{free: 100}, nil, &balances{free: 50}, nil},
		{"transfer between two wallets", domain.TRANSACTION_TRANSFER, &balances{free: 100}, &balances{}, &balances{free: 50}, &balances{free: 50}},
		{"yield into a single wallet", domain.TRANSACTION_YIELD, nil, &balances{free: 10}, nil, &balances{free: 60}},
		{"yield generated by another wallet does not debit it", domain.TRANSACTION_YIELD, &balances{free: 100}, &balances{}, &balances{free: 100}, &balances{free: 50}},
		{"sale without buyer wallet", domain.TRANSACTION_SALE, nil, &balances{}, nil, &balances{free: 50}},
		{"sale with buyer wallet", domain.TRANSACTION_SALE, &balances{free: 100}, &balances{}, &balances{free: 50}, &balances{free: 50}},
		{"fee without revenue wallet", domain.TRANSACTION_FEE, &balances{free: 100}, nil, &balances{free: 50}, nil},
		{"fee paid to a revenue wallet", domain.TRANSACTION_FEE, &balances{free: 100}, &balances{free: 5}, &balances{free: 50}, &balances{free: 55}},
		{"purchase without seller wallet", domain.TRANSACTION_PURCHASE, &balances{free: 100}, nil, &balances{free: 50}, nil},
		{"purchase paid to a seller wallet", domain.TRANSACTION_PURCHASE, &balances{free: 100}, &balances{}, &balances{free: 50}, &balances{free: 50}},
		{"reserve", domain.TRANSACTION_RESERVE, &balances{free: 100}, nil, &balances{free: 50, reserved: 50}, nil},
		{"release", domain.TRANSACTION_RELEASE, &balances{reserved: 50}, nil, &balances{free: 50}, nil},
		{"hold", domain.TRANSACTION_HOLD, &balances{free: 100}, nil, &balances{free: 50, hold: 50}, nil},
		{"unhold", domain.TRANSACTION_UNHOLD, &balances{hold: 50}, nil, &balances{free: 50}, nil},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			source := newTestWallet("source", domain.WALLET_CHECKING, test.source)
			destination := newTestWallet("destination", domain.WALLET_INVESTMENT, test.destination)
			transaction := testTransaction(test.transactionType, 50, source, destination)

			if err := validateTransaction(transaction); err != nil {
				t.Fatal(err)
			}
			if err := applyTransaction(transaction); err != nil {
				t.Fatal(err)
			}

			assertBalances(t, "source", source, test.wantSource)
			assertBalances(t, "destination", destination, test.wantDestination)
		})
	}
}

// NOTE - an amount greater than the available balance must fail without changing any wallet (no partial transfer).
func TestApplyTransactionInsufficientBalanceKeepsWalletsUnchanged(t *testing.T) {
	tests := []struct {
		name            string
		transactionType domain.TransactionType
		source          *balances
		destination     *balances
	}{
		{"withdrawal", domain.TRANSACTION_WITHDRAWAL, &balances{free: 100}, nil},
		{"transfer", domain.TRANSACTION_TRANSFER, &balances{free: 100}, &balances{free: 10}},
		{"sale with buyer wallet", domain.TRANSACTION_SALE, &balances{free: 100}, &balances{free: 10}},
		{"fee without revenue wallet", domain.TRANSACTION_FEE, &balances{free: 100}, nil},
		{"fee paid to a revenue wallet", domain.TRANSACTION_FEE, &balances{free: 100}, &balances{free: 10}},
		{"purchase paid to a seller wallet", domain.TRANSACTION_PURCHASE, &balances{free: 100}, &balances{free: 10}},
		{"reserve", domain.TRANSACTION_RESERVE, &balances{free: 100}, nil},
		{"release", domain.TRANSACTION_RELEASE, &balances{free: 10, reserved: 100}, nil},
		{"hold", domain.TRANSACTION_HOLD, &balances{free: 100}, nil},
		{"unhold", domain.TRANSACTION_UNHOLD, &balances{free: 10, hold: 100}, nil},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			source := newTestWallet("source", domain.WALLET_CHECKING, test.source)
			destination := newTestWallet("destination", domain.WALLET_CHECKING, test.destination)
			transaction := testTransaction(test.transactionType, 150, source, destination)

			if err := validateTransaction(transaction); err != nil {
				t.Fatal(err)
			}
			err := applyTransaction(transaction)
			if !errors.Is(err, ErrTransactionFailed) {
				t.Fatalf("expected transaction failure, got %v", err)
			}

			assertBalances(t, "source", source, test.source)
			assertBalances(t, "destination", destination, test.destination)
		})
	}
}

// NOTE - applying a transaction and then its reversal must restore the initial balances of every wallet.
func TestReversalRestoresOriginalBalances(t *testing.T) {
	tests := []struct {
		name            string
		transactionType domain.TransactionType
		source          *balances
		destination     *balances
	}{
		{"deposit", domain.TRANSACTION_DEPOSIT, nil, &balances{free: 10}},
		{"withdrawal", domain.TRANSACTION_WITHDRAWAL, &balances{free: 100}, nil},
		{"transfer", domain.TRANSACTION_TRANSFER, &balances{free: 100}, &balances{free: 10}},
		{"yield into a single wallet", domain.TRANSACTION_YIELD, nil, &balances{free: 10}},
		{"yield generated by another wallet", domain.TRANSACTION_YIELD, &balances{free: 100}, &balances{free: 10}},
		{"sale without buyer wallet", domain.TRANSACTION_SALE, nil, &balances{free: 10}},
		{"sale with buyer wallet", domain.TRANSACTION_SALE, &balances{free: 100}, &balances{free: 10}},
		{"fee without revenue wallet", domain.TRANSACTION_FEE, &balances{free: 100}, nil},
		{"fee paid to a revenue wallet", domain.TRANSACTION_FEE, &balances{free: 100}, &balances{free: 10}},
		{"purchase without seller wallet", domain.TRANSACTION_PURCHASE, &balances{free: 100}, nil},
		{"purchase paid to a seller wallet", domain.TRANSACTION_PURCHASE, &balances{free: 100}, &balances{free: 10}},
		{"reserve", domain.TRANSACTION_RESERVE, &balances{free: 100}, nil},
		{"release", domain.TRANSACTION_RELEASE, &balances{reserved: 100}, nil},
		{"hold", domain.TRANSACTION_HOLD, &balances{free: 100}, nil},
		{"unhold", domain.TRANSACTION_UNHOLD, &balances{hold: 100}, nil},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			source := newTestWallet("source", domain.WALLET_CHECKING, test.source)
			destination := newTestWallet("destination", domain.WALLET_INVESTMENT, test.destination)

			origin := testTransaction(test.transactionType, 50, source, destination)
			if err := validateTransaction(origin); err != nil {
				t.Fatal(err)
			}
			if err := applyTransaction(origin); err != nil {
				t.Fatal(err)
			}
			origin.Status = domain.TRANSACTION_COMPLETED

			reversal := testReversal(origin, source, destination)
			if err := validateTransaction(reversal); err != nil {
				t.Fatal(err)
			}
			if err := applyTransaction(reversal); err != nil {
				t.Fatal(err)
			}

			assertBalances(t, "source", source, test.source)
			assertBalances(t, "destination", destination, test.destination)
		})
	}
}

func TestReversalFailsWhenBalanceWasAlreadySpent(t *testing.T) {
	source := newTestWallet("source", domain.WALLET_CHECKING, &balances{free: 100})
	destination := newTestWallet("destination", domain.WALLET_CHECKING, &balances{})

	origin := testTransaction(domain.TRANSACTION_TRANSFER, 50, source, destination)
	if err := applyTransaction(origin); err != nil {
		t.Fatal(err)
	}
	origin.Status = domain.TRANSACTION_COMPLETED
	destination.FreeBalance = 20

	reversal := testReversal(origin, source, destination)
	if err := applyTransaction(reversal); !errors.Is(err, ErrTransactionFailed) {
		t.Fatalf("expected transaction failure, got %v", err)
	}
	assertBalances(t, "source", source, &balances{free: 50})
	assertBalances(t, "destination", destination, &balances{free: 20})
}

func TestReversalWallets(t *testing.T) {
	sourceID, destinationID := "source", "destination"

	transfer := &domain.Transaction{Type: domain.TRANSACTION_TRANSFER, SourceWalletID: &sourceID, DestinationWalletID: &destinationID}
	gotSource, gotDestination := getReversalWalletIDs(transfer)
	if gotSource == nil || *gotSource != destinationID || gotDestination == nil || *gotDestination != sourceID {
		t.Fatalf("expected transfer reversal to swap wallets, got source=%v destination=%v", gotSource, gotDestination)
	}

	hold := &domain.Transaction{Type: domain.TRANSACTION_HOLD, SourceWalletID: &sourceID}
	gotSource, gotDestination = getReversalWalletIDs(hold)
	if gotSource == nil || *gotSource != sourceID || gotDestination != nil {
		t.Fatalf("expected hold reversal to keep the same wallet, got source=%v destination=%v", gotSource, gotDestination)
	}

	yield := &domain.Transaction{Type: domain.TRANSACTION_YIELD, SourceWalletID: &sourceID, DestinationWalletID: &destinationID}
	gotSource, gotDestination = getReversalWalletIDs(yield)
	if gotSource == nil || *gotSource != destinationID || gotDestination != nil {
		t.Fatalf("expected yield reversal to leave out the wallet that generated it, got source=%v destination=%v", gotSource, gotDestination)
	}

	fee := &domain.Transaction{Type: domain.TRANSACTION_FEE, SourceWalletID: &sourceID, DestinationWalletID: &destinationID}
	gotSource, gotDestination = getReversalWalletIDs(fee)
	if gotSource == nil || *gotSource != destinationID || gotDestination == nil || *gotDestination != sourceID {
		t.Fatalf("expected fee reversal to move funds from the revenue wallet back to the payer, got source=%v destination=%v", gotSource, gotDestination)
	}
}

// newTestWallet returns nil when the wallet does not take part in the transaction.
func newTestWallet(id string, walletType domain.WalletType, state *balances) *domain.Wallet {
	if state == nil {
		return nil
	}
	return &domain.Wallet{
		ID:              id,
		Type:            walletType,
		Status:          domain.WALLET_ACTIVE,
		AssetID:         "asset",
		FreeBalance:     state.free,
		ReservedBalance: state.reserved,
		HoldBalance:     state.hold,
	}
}

func testTransaction(transactionType domain.TransactionType, amount int64, source, destination *domain.Wallet) *domain.Transaction {
	return &domain.Transaction{
		Type:              transactionType,
		Amount:            amount,
		SourceWallet:      source,
		DestinationWallet: destination,
	}
}

// testReversal builds a reversal the same way TransactionService.Create does: wallets come from the original transaction.
func testReversal(origin *domain.Transaction, wallets ...*domain.Wallet) *domain.Transaction {
	findWallet := func(id *string) *domain.Wallet {
		if id == nil {
			return nil
		}
		for _, wallet := range wallets {
			if wallet != nil && wallet.ID == *id {
				return wallet
			}
		}
		return nil
	}

	sourceID, destinationID := getReversalWalletIDs(origin)
	return &domain.Transaction{
		Type:              domain.TRANSACTION_REVERSAL,
		Amount:            origin.Amount,
		ReversalOrigin:    origin,
		SourceWallet:      findWallet(sourceID),
		DestinationWallet: findWallet(destinationID),
	}
}

func assertBalances(t *testing.T, label string, wallet *domain.Wallet, want *balances) {
	t.Helper()

	if wallet == nil || want == nil {
		if wallet != nil || want != nil {
			t.Fatalf("unexpected %s wallet participation: wallet=%v want=%v", label, wallet, want)
		}
		return
	}
	if wallet.FreeBalance != want.free || wallet.ReservedBalance != want.reserved || wallet.HoldBalance != want.hold {
		t.Fatalf("unexpected %s balances: free=%d reserved=%d hold=%d, want free=%d reserved=%d hold=%d",
			label, wallet.FreeBalance, wallet.ReservedBalance, wallet.HoldBalance, want.free, want.reserved, want.hold)
	}
}
